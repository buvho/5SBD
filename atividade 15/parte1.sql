CREATE OR REPLACE VIEW vw_empregados_depto AS
SELECT 
    e.id_empregado,
    e.nome,
    e.cargo,
    e.salario,
    d.nome_depto
FROM tb_empregados e
CROSS JOIN tb_departamentos_trg d
WHERE d.nome_depto = 'TECNOLOGIA';

CREATE OR REPLACE TRIGGER trg_vw_empregados_depto_ii
INSTEAD OF INSERT ON vw_empregados_depto
FOR EACH ROW
DECLARE
    v_qtd_depto NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_qtd_depto
      FROM tb_departamentos_trg
     WHERE nome_depto = UPPER(TRIM(:NEW.nome_depto));

    IF v_qtd_depto = 0 THEN
        INSERT INTO tb_departamentos_trg (nome_depto)
        VALUES (UPPER(TRIM(:NEW.nome_depto)));
    END IF;

    INSERT INTO tb_empregados (nome, cargo, salario)
    VALUES (:NEW.nome, :NEW.cargo, :NEW.salario);
END trg_vw_empregados_depto_ii;
/

